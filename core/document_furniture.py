"""
Рамка бланка — не содержание документа.

Зачем это нужно. У обычного документа по ГОСТ 2.104 — руководства,
паспорта, инструкции, СТП — на каждой странице стоит рамка с графами:
«Подпись и дата», «Инв. № подл.», «Взам. инв. №», «Перв. примен.»,
«Формат А4», строка «Изм. Лист № документа Подпись Дата». На скане
распознавание читает их как обычный текст страницы, и дальше с ними
случаются две разные неприятности.

**Первая: графа становится отдельным чанком.** Замер по 50 документам с
прода (2901 чанк): чанков короче 120 символов 1195, то есть 41,2 %, и 270
из них — ровно эта рамка. «Формат А4» встречается отдельным чанком 72
раза, «Формат Ad» (то же слово, прочитанное иначе) — ещё 10, «Изм Лист
№ документа Подпись Дата» — много раз на документ. У каждого свой вектор,
и каждый соперничает в поиске с настоящим содержанием.

**Вторая, и она хуже: графа попадает в середину связного текста.** Боковые
графы рамки стоят вдоль листа, повёрнутые, и распознавание вставляет их
туда, где в строке кончилось место. В настоящем чанке ТАДУ 681821.005 РЭ
стоит:

    ...растворы для дезактивации наружных поверхно- Подпись и дата стей.

Слово «поверхностей» разрезано подписью графы. Такой чанк длинный, по
всем счётчикам здоровый, и ни один замер размера его не покажет — а
прочитать его нельзя. Это и есть то, о чём просил заказчик: «чтобы
извлечённый текст можно было понять».

Что делает модуль. Две операции, обе осторожные и обе на одном флаге
`SCAN_DROP_FRAME_FURNITURE`:

1. Фрагмент, в котором **кроме рамки ничего нет**, снимается целиком.
   Критерий — не похожесть, а исчерпание: из текста вычитаются подписи
   граф и то, чем графа заполняется (дата, инвентарный номер, обозначение
   документа, одна фамилия, пометка `[TABLE]`, номера листов), и если не
   осталось ни одного слова — фрагмент был рамкой. Если осталось хоть
   что-то, фрагмент остаётся целиком: лучше лишний чанк, чем потерянное
   требование.
2. Подпись графы **внутри** связного текста вырезается, и разрезанное ею
   слово сращивается. Вырезается только та, что стоит посреди фразы:
   слева буква или знак переноса, справа строчная буква. Подпись в начале
   или в конце абзаца не трогается — там она может быть и содержанием
   (в паспорте графа «Подпись и дата» — часть формы, а не рамка).

Чего модуль не делает. Он не судит о странице и не считает долей: решение
принимается по одному фрагменту и только по тексту. Он не трогает таблицы
(`table_data`), чертежи и формулы. Он не удаляет ничего, кроме подписей
граф из закрытого списка и их значений, и ни одна цифра содержания под
правило не попадает: число удаляется только тогда, когда оно стоит при
подписи графы и в фрагменте нет больше ни одного слова.

Связи. Вызывается из `core/contract_finalize.finalize_fragments` для
текстовых фрагментов — там же, где `mixed_script` и `designation_repair`,
то есть до `fragment_id` и до извлечения фактов: в индекс и в факты должен
уйти тот текст, который увидит заказчик. Идемпотентно.
"""

from __future__ import annotations

import logging
import re
from typing import List, Optional, Tuple

from core.config import settings
from core.models.contract import Fragment

logger = logging.getLogger(__name__)

# Подписи граф рамки по ГОСТ 2.104, как они приходят с распознавания —
# включая прочтения, встреченные на проде: «Baam. инв №» вместо «Взам.
# инв. №», «И3м» вместо «Изм.», «Л ист» вместо «Лист», «Формат Ad» вместо
# «Формат А4». Образец допускает лишние пробелы и точки между словами и
# не допускает ничего другого: подпись графы узнаётся буква в букву.
_LABELS: Tuple[str, ...] = (
    r"подп(?:ись|\.)?\s*и\s*дата",
    r"подп(?:ись|\.)?",
    r"инв\.?\s*№?\s*подл\.?",
    r"инв\.?\s*№?\s*дубл\.?",
    r"(?:взам|baam|bзam)\.?\s*инв\.?\s*№?",
    r"перв\.?\s*(?:примен(?:ение)?|примен\.?)",
    r"справ\.?\s*№?",
    r"формат",
    r"лист(?:ов)?",
    r"л\s?ист",
    r"(?:изм|и3м)\.?",
    r"№?\s*докум(?:ента|\.)?",
    r"дата",
)
# Слово извещения об изменении. Строка с ним — не рамка, а запись о
# ревизии документа: «Изм.: 1 Зам. ТАДУ.655-25 2.09.19» рассказывает,
# каким извещением и когда документ изменён, и это содержание. Любой
# фрагмент с этим словом остаётся целиком, даже если всё остальное в нём
# похоже на графы: заголовок графы изменений («Изм. Лист № документа
# Подпись Дата») такого слова не несёт, а заполненная строка несёт.
_CHANGE_NOTICE = re.compile(r"\b(?:зам|замен\w*|изв|извещ\w*)\b\.?", re.IGNORECASE)
# Латинский обрывок внутри текста, который в остальном весь из граф:
# распознавание так портит кириллическую подпись графы («[Tver» вместо
# «[Изм», «P3» вместо «РЭ»). Вычитается только там, где подписей граф
# набралось не меньше `_GARBLE_MIN_LABELS`: в обычном тексте латинский
# токен — это слово, а не порча.
_LATIN_SCRAP = re.compile(r"\b[A-Za-z]{1,5}\b")
_GARBLE_MIN_LABELS = 3
# Чем графа заполняется: дата в любом виде, инвентарный номер, номер листа,
# обозначение документа, одна фамилия с большой буквы, метка таблицы,
# обозначение формата. Всё это удаляется **только** при вычитании (операция
# 1) и только вместе с подписями граф.
_FILLERS: Tuple[str, ...] = (
    r"\[TABLE\]",
    r"\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}",      # 12.01.23
    r"\d{1,2}[.\-/]\d{4}",                      # 06.2023
    r"[A-ZА-ЯЁ]{2,4}\.?\s?\d[\d.\-]*[A-ZА-ЯЁ\d]*",  # ТАДУ 681821.005РЭ
    r"[АA][\dd]\b",                             # А4, Ad
    r"[А-ЯЁ][а-яё]{2,}(?:ова|ев|ин|ко|ян|ова)\b",   # фамилия в графе
    r"[А-ЯЁ][а-яё]{3,}\b",                      # одна фамилия с большой буквы
    r"\d+(?:[-–]\d+)?",                         # 1405, 1221-310
    r"№",
)
_LABEL_RE = re.compile(r"(?:%s)" % "|".join(_LABELS), re.IGNORECASE)
_FILLER_RE = re.compile(r"(?:%s)" % "|".join(_FILLERS))
# Что остаётся незначащим после вычитания: знаки, скобки распознавания.
_RESIDUE = re.compile(r"[\s.,:;|/\\\[\]()«»\"'`~=+\-–—*•_©®°№]+")
# Слово содержания: три и более букв подряд. По нему и решается, осталось
# ли в тексте хоть что-то.
_WORD = re.compile(r"[А-Яа-яЁёA-Za-z]{3,}")

# Подпись графы посреди фразы: слева буква или знак переноса, справа
# строчная буква. Именно такой разрыв даёт боковая графа, вставленная
# распознаванием в строку, и только он вырезается.
#
# Вырезаются **не** все подписи из `_LABELS`, а только составные и
# различимые. Одно частое слово — «дата», «лист», «подпись», «формат» —
# вырезать из связного текста нельзя: во фразе «в этот лист вносятся
# изменения» слева буква, справа строчная буква, и правило вырезало бы
# слово содержания. Проверено тестом: именно этот случай правило и
# портило, пока список был общим.
_SPLICE_LABELS: Tuple[str, ...] = (
    r"подп(?:ись|\.)?\s*и\s*дата",
    r"инв\.?\s*№?\s*подл\.?",
    r"инв\.?\s*№?\s*дубл\.?",
    r"(?:взам|baam|bзam)\.?\s*инв\.?\s*№?",
    r"перв\.?\s*примен(?:ение)?\.?",
    r"справ\.?\s*№",
    # Со знаком «№» обязательно: слово «инвентарный» в содержании под
    # правило не попадает, а графа рамки без «подл.»/«дубл.» — попадает.
    r"инв\.?\s*№",
    r"формат\s*[АA][\dd]",
    r"(?:изм|и3м)\.?\s*лист\s*№?\s*докум(?:ента|\.)?\s*подп(?:ись|\.)?\s*дата",
)
_SPLICE = re.compile(
    r"(?P<left>[А-Яа-яЁёA-Za-z]-?)"
    r"\s+(?:%s)(?:\s+(?:%s))*\s+"
    r"(?P<right>[а-яёa-z])" % ("|".join(_SPLICE_LABELS), "|".join(_SPLICE_LABELS)),
    re.IGNORECASE,
)
# Две и более подписи граф подряд — это рамка, где бы она ни стояла, в том
# числе на стыке двух фраз: «...по эксплуатации. Baam. инв № I Инв. № ay
# ВНИМАНИЕ!». Слова содержания так подряд не стоят, поэтому соседи здесь
# не проверяются; между подписями допускается немного мусора
# распознавания («№ I Инв.»), и только он.
_SPLICE_RUN = re.compile(
    r"(?:%s)(?:[\s.,|/\\[\]()I1lАA]{1,8}(?:%s)){1,}[.\s]*"
    % ("|".join(_SPLICE_LABELS), "|".join(_SPLICE_LABELS)),
    re.IGNORECASE,
)
# Сколько букв должно быть в тексте, чтобы считать его связным и искать в
# нём вставленную графу. На коротком фрагменте вырезать нечего: он либо
# рамка целиком (операция 1), либо содержание.
_PROSE_MIN_CHARS = 200


# Перенос строки, отданный распознаванием как дефис с пробелом:
# «эксплуата- ции», «поверхно- стей», «ОСНОВ- ными». Слева буквы и дефис
# вплотную к ним, справа строчная буква — то есть продолжение того же
# слова, а не второе слово составного.
_HYPHEN_BREAK = re.compile(r"\b([А-Яа-яЁёA-Za-z]{2,})-[ \t]+([а-яёa-z])")
# Первые части составных слов: у них дефис свой, и сращивать нельзя.
# Список неполон заведомо — это известная цена флага, и она названа в
# `README.md`. Ошибка здесь безобидна в одну сторону (слово осталось
# разорванным, как и было) и портит слово в другую, поэтому список
# пополняется по находкам, а не угадывается широко.
_COMPOUND_HEADS = frozenset({
    "научно", "технико", "физико", "химико", "электро", "радио", "теле",
    "контрольно", "приёмо", "приемо", "планово", "пуско", "монтажно",
    "ремонтно", "сварочно", "измерительно", "выпукло", "северо", "юго",
    "давление", "вакуум",
})


def enabled() -> bool:
    return bool(getattr(settings, "SCAN_DROP_FRAME_FURNITURE", False))


def join_enabled() -> bool:
    return bool(getattr(settings, "SCAN_JOIN_HYPHENATED_WORDS", False))


def without_hyphen_breaks(text: str) -> Tuple[str, int]:
    """
    Текст, в котором слова, разорванные переносом, сращены; и сколько их.

    Почему это вообще нужно отдельным правилом: `core/providers/ocr_cleanup.py`
    на этом месте прямо отказывается (««изде-» — половина слова до
    переноса, словаря для неё нет»), и отказ верен для **исправления**
    такой половины. Но сращивание словаря не требует: обе половины
    прочитаны, нужно только убрать перенос, который распознавание отдало
    дефисом.

    Составное слово не сращивается: его первая часть — в `_COMPOUND_HEADS`.
    """
    joined = 0

    def join(match: "re.Match[str]") -> str:
        nonlocal joined
        head, tail = match.group(1), match.group(2)
        if head.lower() in _COMPOUND_HEADS:
            return match.group(0)
        joined += 1
        return head + tail

    out = _HYPHEN_BREAK.sub(join, text)
    return out, joined


def is_furniture(text: Optional[str]) -> bool:
    """
    В тексте нет ничего, кроме рамки бланка.

    Решается вычитанием: убрать подписи граф, затем то, чем графы
    заполняются, затем знаки — и посмотреть, осталось ли слово. Требуется
    ещё, чтобы хотя бы одна подпись графы в тексте была: фрагмент из одних
    цифр рамкой не объявляется, это не её признак.
    """
    body = " ".join((text or "").split())
    if not body or _CHANGE_NOTICE.search(body):
        return False
    labels = _LABEL_RE.findall(body)
    if not labels:
        return False
    rest = _FILLER_RE.sub(" ", _LABEL_RE.sub(" ", body))
    if len(labels) >= _GARBLE_MIN_LABELS:
        rest = _LATIN_SCRAP.sub(" ", rest)
    rest = _RESIDUE.sub(" ", rest)
    return not _WORD.search(rest)


def without_splices(text: str) -> Tuple[str, int]:
    """
    Текст без подписей граф, вставленных посреди фразы, и число вырезанных.

    Разрезанное слово сращивается: «поверхно- Подпись и дата стей» ->
    «поверхностей». Знак переноса при сращивании снимается — он и был
    переносом, а не дефисом слова: справа стоит строчная буква, то есть
    продолжение того же слова, а не второе слово составного.
    """
    if len(text) < _PROSE_MIN_CHARS:
        return text, 0
    cut = 0

    def join(match: "re.Match[str]") -> str:
        nonlocal cut
        cut += 1
        left, right = match.group("left"), match.group("right")
        if left.endswith("-"):
            return left[:-1] + right
        return left + " " + right

    out = _SPLICE.sub(join, text)

    def drop(match: "re.Match[str]") -> str:
        nonlocal cut
        cut += 1
        return " "

    out = _SPLICE_RUN.sub(drop, out)
    return re.sub(r"[ \t]{2,}", " ", out), cut


def apply(fragments: List[Fragment]) -> List[Fragment]:
    """
    Снимает фрагменты-рамки и вырезает графы из середины связного текста.

    Возвращает новый список: фрагмент-рамка в него не попадает. Порядок
    остальных не меняется, `position.order` проставляется позже
    (`core/contract_finalize.finalize_fragments`), поэтому снятие фрагмента
    нумерацию не ломает; `fragment_id` считается от содержимого, а не от
    места в списке.
    """
    if not (enabled() or join_enabled()):
        return fragments
    kept: List[Fragment] = []
    dropped = spliced = joined = 0
    for fragment in fragments:
        if fragment.type != "text" or fragment.content.table_data is not None:
            kept.append(fragment)
            continue
        text = fragment.content.text or ""
        if enabled():
            if is_furniture(text):
                dropped += 1
                continue
            text, cut = without_splices(text)
            spliced += cut
        if join_enabled():
            # Сращивание — после вырезания графы: графа, вставленная в
            # перенос, сама и была причиной разрыва, и после её снятия
            # переноса на том месте уже нет.
            text, count = without_hyphen_breaks(text)
            joined += count
        if text != (fragment.content.text or ""):
            fragment.content.text = text
        kept.append(fragment)
    if dropped or spliced or joined:
        logger.info("Рамка бланка: снято фрагментов %d, вырезано граф из текста %d, "
                    "сращено переносов %d", dropped, spliced, joined)
    return kept
