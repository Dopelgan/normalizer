    # времени, поэтому отдельный флаг. По умолчанию выключено.
    DRAWING_GENRE_GATE_STAMP_OCR: bool = False
    # Чертёж, прочитанный моделью целиком, но без измеренной полноты и
    # калиброванной уверенности, остаётся на проверке пофрагментно
    # (review_required), а документ не становится partial. Partial только при
    # реальной потере: непрочитанные области, лист не распознан или пропущен
    # по сроку (core/drawing_quality.py). По умолчанию выключено.
    DRAWING_UNMEASURED_NOT_PARTIAL: bool = False
    # Полное чтение листа-картинки (JPG/PNG/TIFF): лист целиком уходит в
    # Qwen-VL со штампом и отдельным проходом «перепиши весь текст листа»,
    # даже если MinerU нарезал из него картинки или лестница назвала лист
    # текстом, а растровый детектор видит на нём рамку чертежа. Текст листа
    # ложится в content.text фрагмента drawing; непрочитанные области
    # листа, текст которого переписан целиком, потерей не считаются
    # (core/drawing_processor.py, core/drawing_quality.py). По умолчанию выключено.
    DRAWING_IMAGE_FULL_READ: bool = False
    # Длинная сторона листа и потолок ответа для прохода «весь текст листа»:
    # мелкий текст граф и примечаний на A3 при 2000 px не читается.
    DRAWING_TRANSCRIBE_MAX_SIDE: int = 2800
    DRAWING_TRANSCRIBE_MAX_TOKENS: int = 8192
    # Плотный лист (электросхема, табличка) не помещается в потолок ответа:
    # ответ обрывается и раньше пропадал целиком как «не-JSON». С флагом
    # строки оборванного ответа сохраняются, а лист дочитывается частями
    # (сетка GRID x GRID с перекрытием OVERLAP доли стороны); часть, которая
    # сама оборвалась, делится ещё раз, пока глубина не достигнет DEPTH.
    # Строки частей сливаются без повторов из перекрытия. Часть, которую
    # прочитать не удалось, — непрочитанная область листа, и документ
    # partial (core/providers/qwen_client.py). По умолчанию выключено.
    DRAWING_TRANSCRIBE_TILES: bool = False
    DRAWING_TRANSCRIBE_TILE_GRID: int = 2
    DRAWING_TRANSCRIBE_TILE_OVERLAP: float = 0.06
    DRAWING_TRANSCRIBE_TILE_DEPTH: int = 2
    # Сколько частей листа читается одновременно (vLLM --max-num-seqs 16).
    DRAWING_TRANSCRIBE_TILE_PARALLEL: int = 4
    # Проход «лист целиком» (надписи с их местами) считает ответы по общему
    # потолку QWEN_MAX_TOKENS = 4096. На плотном листе список annotations в
    # него не влезает: ответ обрывается, спасаются только дописанные надписи,
    # а хвост списка пропадает молча — оборванный ответ остаётся успешным
    # ответом. С флагом у прохода свой потолок DRAWING_SHEET_MAX_TOKENS.
    #
    # 12288 выбрано по бюджету хоста, а не «побольше»: пул KV у vLLM
    # выделяется при старте (101 282 токена на 5.34 ГиБ, fp8), и потолок
    # ответа не просит у видеокарты ни одного лишнего байта — он только
    # занимает больше места в этом пуле на время вызова. Лист 2000 px даёт
    # около 4.4 тыс. токенов запроса, то есть вызов стоит до 16.7 тыс.
    # токенов пула: шесть таких вызовов разом пул ещё держит, а --max-model-len
    # 32768 оставляет двойной запас. MinerU и два TEI от этого ничего не
    # теряют: доля видеокарты у vLLM (--gpu-memory-utilization) не меняется.
    # Цена — время: модель отдаёт около 82 токенов/с, поэтому ответ, который
    # упёрся бы в 4096, идёт дольше. Потолок не цель, а предел: лист, на
    # котором надписи кончились, отвечает ровно столько же, сколько раньше
    # (core/providers/qwen_client.py). По умолчанию выключено.
    DRAWING_SHEET_HIGH_TOKENS: bool = False
    DRAWING_SHEET_MAX_TOKENS: int = 12288
    # Лист, ответ по которому всё равно оборвался, читается заново частями:
    # та же сетка GRID x GRID с перекрытием OVERLAP, что и у прохода «весь
    # текст листа» (tile_boxes), а списки надписей частей сливаются без
    # повторов из перекрытия — по тексту надписи и её месту на листе.
    # Части читаются только если обрыв действительно случился: на целом
    # ответе флаг не стоит ни одного вызова. Делений вглубь нет — часть,
    # которая тоже оборвалась, остаётся непрочитанной областью листа, и лист
    # честно помечается недочитанным, а не читается ещё 16 раз сверх бюджета
    # (core/providers/qwen_client.py). По умолчанию выключено.
    DRAWING_SHEET_TILES: bool = False
    DRAWING_SHEET_TILE_GRID: int = 2
    DRAWING_SHEET_TILE_OVERLAP: float = 0.06
    # Сколько секунд бюджета листа (DRAWING_TIME_BUDGET) оставить проходам,
    # которые идут ПОСЛЕ чтения листа: «весь текст листа» со своими частями,
    # штамп, таблицы. Части листа не начинаются, если не успеют закончиться
    # до этого запаса.
    #
    # Бюджет здесь именно на ЛИСТ, а не на документ: `started` ставится
    # внутри DrawingProcessor.process, а он вызывается на каждый лист
    # (core/drawing_processor.py). Все участники каскада ниже делят один и
    # тот же бюджет листа, поэтому запас считается от него.
    #
    # Документ ограничен отдельно и куда щедрее: process_document объявляет
    # PARSE_TASK_SOFT_TIME_LIMIT/PARSE_TASK_TIME_LIMIT (ingest/tasks.py),
    # по умолчанию 3600/3900 с, а в цикле листов стоит проверка
    # deadline.remaining() < VLM_TIMEOUT против этого срока за вычетом
    # PARSE_DEADLINE_RESERVE. CELERY_TASK_TIME_LIMIT = 600 к разбору
    # документа отношения не имеет — это предел других задач. Отсюда и
    # выбор средства: поднять сам DRAWING_TIME_BUDGET было бы можно, но
    # тогда один лист съедает больше общего срока документа, и на
    # многолистовом альбоме следующие листы пропускаются с
    # DRAWING_SKIPPED_NO_TIME — а это уже потеря, которая доходит до
    # человека. Запас такого размена не делает.
    #
    # Это не перестраховка, а защита от каскада. Если проход листа съест
    # бюджет, частям прохода «весь текст листа» времени не останется, и
    # тогда transcript_complete=false плюс области kind=transcript_tile —
    # а они считаются потерей всегда (core/drawing_quality.py), и документ
    # становится partial, то есть уходит человеку. Качество чтения листа
    # человека касаться не должно, поэтому дочитывание частями обязано
    # укладываться в свою долю бюджета, а не занимать его целиком.
    #
    # 120 с взято по замеру прода: работа после прохода листа занимает
    # median 10.7 с, p90 29.7 с, p99 111.4 с (n=326). Запас 120 с покрывает
    # 99.7% листов и оставляет проходу листа 300 с из 420 — при том что сам
    # проход сегодня не превышает 55.5 с, а с поднятым потолком ограничен
    # таймаутом запроса (QWEN_TIMEOUT).
    DRAWING_SHEET_TILE_RESERVE: int = 120
    # Доля стороны листа, ближе которой две надписи с одним текстом —
    # одна надпись, прочитанная двумя перекрывшимися частями. Тот же текст
    # в другом месте листа сохраняется: «⌀8» стоит у каждого отверстия.
    DRAWING_SHEET_TILE_NEAR: float = 0.05
    # Учёта потерянных прочтений под флагом нет: что случилось с ответом
    # прохода «лист целиком», пишется в payload листа всегда
    # (sheet_answer_cut, sheet_annotations_lost, sheet_annotations_complete,
    # sheet_reparse_candidate с причиной — core/drawing_processor.py). Это
    # факты о разборе, а не эскалация, и считать обрывы нужно по сохранённым
    # данным, а не грепом по логам воркера. Человека эти ключи никуда не
    # отправляют: ни warnings, ни missing_regions они не пополняют, и
    # документ от обрыва ответа partial не становится — файл уходит человеку
    # только за кластером, именем и конфликтом версий.
