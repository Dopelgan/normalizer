    """Единая точка конфигурации сервиса. Значения берутся из .env / окружения."""

    # ------------------------------------------------------------------ Общие
    TZ: str = "UTC"
    LOG_LEVEL: str = "INFO"
    # Формат логов: json — строка на событие для сборщика логов, text — для
    # чтения глазами. Замеры времени этапов пишутся событиями `stage`, и
    # разбирать их удобнее в json.
    LOG_FORMAT: str = "json"
    # Логи доступа uvicorn на каждый опрос /health и /metrics забивают ленту.
    QUIET_ACCESS_LOG: bool = True
    # Порт метрик Prometheus у процессов без своего веб-сервера (воркеры).
    # У сервисов FastAPI метрики отдаёт ручка /metrics.
    METRICS_WORKER_PORT: int = 9100

    # ------------------------------------------------------------ База данных
    POSTGRES_USER: str = "knowledge_user"
    POSTGRES_PASSWORD: str = "secure_password"
    POSTGRES_DB: str = "knowledge"
    POSTGRES_PORT: int = 5432
    DATABASE_URL: str = "postgresql://knowledge_user:secure_password@postgres:5432/knowledge"

    # --------------------------------------------------------- Redis / Celery
    REDIS_PORT: int = 6379
    CELERY_BROKER_URL: str = "redis://redis:6379/0"
    CELERY_RESULT_BACKEND: str = "redis://redis:6379/0"
    EVENT_BROKER_URL: str = "redis://redis:6379/1"

    # ------------------------------------------------------------- Хранилище
    STORAGE_TYPE: str = "local"                 # local | s3
    STORAGE_LOCAL_MOUNT: str = "/data/shared"
    S3_ENDPOINT: Optional[str] = None
    S3_ACCESS_KEY: Optional[str] = None
    S3_SECRET_KEY: Optional[str] = None
    S3_BUCKET: Optional[str] = None
    RAW_PARSE_S3_PREFIX: str = "raw_parse/"

    # Где Parser ищет входные файлы по s3_fileid (контракт RAG <-> Parser).
    SOURCE_PREFIX: str = "documents/"
    # Расширения, которые перебираются, если s3_fileid пришёл без расширения.
    # Значение по умолчанию собирается из core.filetypes — единого реестра
    # поддерживаемых форматов, чтобы список не расходился с ним.
    SOURCE_PROBE_EXTENSIONS: List[str] = ["." + ext for ext in PROBE_ORDER]
    # Бакет вложений чата Backend (на проде — `chat-attachments`). Ключ там —
    # голый uuid в нижнем регистре без расширения, исходное имя файла лежит
    # в метаданных объекта `filename` (URL-encoded). Пусто — поиск во
    # вложениях выключен. Смотрим туда, только если в основном бакете по
    # такому uuid ничего не нашлось.
    S3_ATTACHMENTS_BUCKET: str = ""
    # Куда складываются изображения, вырезанные из PDF.
    ASSETS_PREFIX: str = "assets/"

    # S3 у нас выдан только на чтение. Поэтому всё производное — вырезанные
    # картинки, выправленные растры, сырой JSON парсера — пишется не туда,
    # откуда пришёл документ, а в собственный том сервиса. Провайдер
    # хранилища при S3_READONLY=true читает s3:// из S3, а любую запись
    # уводит в ARTIFACTS_MOUNT. Ставить false стоит только тогда, когда
    # бакет действительно доступен на запись.
    S3_READONLY: bool = True
    ARTIFACTS_MOUNT: str = "/data/shared"
    # Временные файлы (выкачанный из S3 исходник для tesseract, промежуточные
    # растры poppler) держим в том же томе, а не на слое контейнера: он не
    # резиновый, и после падения воркера мусор виден и чистится.
    TEMP_DIR: str = "/data/shared/tmp"

    # ----------------------------------------------------------------- MinerU
    MINERU_VERSION: str = "3.4.5"
    MINERU_PORT: int = 8000
    MINERU_ENDPOINT: str = "http://mineru-api:8000"
    MINERU_TIMEOUT: int = 300
    # Бюджет на страницу: большой скан получает таймаут pages × это значение,
    # если он больше MINERU_TIMEOUT, но не больше 40 % бюджета задачи разбора
    # (остальное — на OCR-фоллбэк и сохранение).
    MINERU_TIMEOUT_PER_PAGE: int = 15
    MINERU_MODEL_CACHE: str = "/models/pdf-extract-kit"
    MINERU_BACKEND: str = "pipeline"
    MINERU_DEFAULT_LANG: str = "east_slavic"
    # Собирать ли для растра текстовый слой построчным распознаванием и
    # сшивать его с блоками MinerU. Стоит одного прохода Tesseract на
    # документ; без него русская проза в ячейках таблиц остаётся LaTeX-кашей.
    OCR_LAYER_ENABLED: bool = True
    # Строки слоя распознавания ниже этой уверенности отбрасываются на тех
    # страницах, где MinerU дал свой текст: Tesseract-мусор («едприяувие = Fe»)
    # иначе уезжает в индекс рядом с текстом MinerU. Только растр (скан,
    # картинка); применяется в core/providers/mineru_parser.py. По умолчанию
    # выключено, значения на проде — в README, раздел «Флаги разбора».
    OCR_LAYER_DROP_LOW_CONFIDENCE: bool = False
    OCR_LAYER_MIN_LINE_CONFIDENCE: float = 0.4
    # Блок, восстановленный из слоя распознавания на странице, где MinerU
    # дал свой текст, отбрасывается, если он повторяет этот текст (доля
    # русских слов, чья основа есть в тексте MinerU той же страницы, не ниже
    # OCR_LAYER_REPEAT_SHARE) или в нём нет ни одного русского слова. На
    # чертеже строка Tesseract идёт через графику и примечания сразу, не
    # попадает ни в одну рамку MinerU и уходит в индекс второй, худшей копией
    # примечаний («Cozobopa», «MEXHONOZUYECKUX»). Только растр; по умолчанию
    # выключено (core/providers/mineru_parser.py).
    OCR_LAYER_DROP_REPEATED: bool = False
    OCR_LAYER_REPEAT_SHARE: float = 0.6
    # Шум распознавания растра (core/providers/ocr_cleanup.py и сшивка в
    # core/providers/text_layer.py). Все три по умолчанию выключены.
    # Выправка слов по словарю моделей Tesseract: латиница в русском слове
    # («Bbod», «TY», «no»), курсивные б/в/д, и/п/н, обрывки линий сетки.
    OCR_WORD_FIX_ENABLED: bool = False
    # Таблица MinerU во весь лист с настоящими строками (спецификация ЕСКД)
    # не снимается защитой рамок FRAME_TABLE_GUARD_ENABLED на скане.
    OCR_KEEP_STRUCTURED_TABLES: bool = False
    # Строки слоя из рамки таблицы, которые возвращались бы текстом
    # (повтор таблицы через линии сетки), ниже этой уверенности
    # отбрасываются. 0 — выключено.
    OCR_TABLE_LINE_MIN_CONFIDENCE: float = 0.0
    # Таблица скана, которую модель таблиц MinerU отдала разметкой и которую
    # не удалось собрать по строкам OCR (типично — альбомная таблица на
    # книжном листе), перечитывается Qwen-VL по вырезке, поставленной прямо
    # по OSD. Не прочитала модель — таблица разбирается на текст
    # (core/providers/table_vlm.py). По умолчанию выключено.
    TABLE_VLM_RETRY_ENABLED: bool = False
    # Не больше стольких перечитываний на документ: каждое — ~15 с GPU.
    TABLE_VLM_MAX_TABLES: int = 8
    # Разрешение, в котором страница рендерится для вырезки таблицы.
    TABLE_VLM_DPI: int = 200
    # Строка Tesseract режется по широкому пробелу, а строки без рамки
    # MinerU собираются в абзацы по колонкам: разворот паспорта в две
    # колонки иначе читается одной строкой через обе.
    OCR_SPLIT_WIDE_GAPS: bool = False
    # Страница с прозой в рамке ЕСКД (ПОК, СТО, ТУ, ТЗ, письма) — текст, а
    # не чертёж (core/providers/page_prose.py). Проверка в опознании листа
    # векторного PDF (core/providers/vector_drawing.py). По умолчанию выключено.
    DRAWING_TEXT_IN_FRAME_ENABLED: bool = False
    # Таблица MinerU на половину листа и больше с прозой внутри — это рамка
    # формата, а не таблица: разбирается в текст по слою
    # (core/providers/text_layer.py, сшивка и векторного слоя, и слоя
    # распознавания). По умолчанию выключено.
    FRAME_TABLE_GUARD_ENABLED: bool = False
    # Классификатор «чертёж или текст в рамке ЕСКД» поверх
    # DRAWING_TEXT_IN_FRAME_ENABLED: (1) лист ТЗ/ПМ/ТУ с вставленным рисунком
    # и штампом текстового документа — страница текста
    # (core/providers/vector_drawing.py); (2) в текстовом документе мелкие
    # картинки (логотип, печать, подпись, гриф «Утверждаю») не уходят в
    # Qwen-VL как чертёж (core/drawing_processor.py). По умолчанию выключено.
    DRAWING_PAGE_CLASSIFIER_ENABLED: bool = False
    # Чертёж, прочитанный моделью целиком, но без измеренной полноты и
    # калиброванной уверенности, остаётся на проверке пофрагментно
    # (review_required), а документ не становится partial. Partial только при
    # реальной потере: непрочитанные области, лист не распознан или пропущен
    # по сроку (core/drawing_quality.py). По умолчанию выключено.
    DRAWING_UNMEASURED_NOT_PARTIAL: bool = False
    # Полное чтение листа-картинки (JPG/PNG/TIFF): лист целиком уходит в
    # Qwen-VL со штампом и отдельным проходом «перепиши весь текст листа»,
    # даже если MinerU нарезал из него картинки или лестница назвала лист
    # текстом, а растровый детектор видит на нём рамку чертежа. Текст листа
    # ложится в content.text фрагмента drawing; непрочитанные области
    # листа, текст которого переписан целиком, потерей не считаются
    # (core/drawing_processor.py, core/drawing_quality.py). По умолчанию выключено.
    DRAWING_IMAGE_FULL_READ: bool = False
    # Длинная сторона листа и потолок ответа для прохода «весь текст листа»:
    # мелкий текст граф и примечаний на A3 при 2000 px не читается.
    DRAWING_TRANSCRIBE_MAX_SIDE: int = 2800
    DRAWING_TRANSCRIBE_MAX_TOKENS: int = 8192
    # Плотный лист (электросхема, табличка) не помещается в потолок ответа:
    # ответ обрывается и раньше пропадал целиком как «не-JSON». С флагом
    # строки оборванного ответа сохраняются, а лист дочитывается частями
    # (сетка GRID x GRID с перекрытием OVERLAP доли стороны); часть, которая
    # сама оборвалась, делится ещё раз, пока глубина не достигнет DEPTH.
    # Строки частей сливаются без повторов из перекрытия. Часть, которую
    # прочитать не удалось, — непрочитанная область листа, и документ
    # partial (core/providers/qwen_client.py). По умолчанию выключено.
    DRAWING_TRANSCRIBE_TILES: bool = False
    DRAWING_TRANSCRIBE_TILE_GRID: int = 2
    DRAWING_TRANSCRIBE_TILE_OVERLAP: float = 0.06
    DRAWING_TRANSCRIBE_TILE_DEPTH: int = 2
    # Сколько частей листа читается одновременно (vLLM --max-num-seqs 16).
    DRAWING_TRANSCRIBE_TILE_PARALLEL: int = 4
    # Скан чертежа в PDF: лист, на котором MinerU не нарезал ни одной
    # картинки (повёрнутый лист, лист-таблица), читается Qwen-VL целиком, даже
    # если на других листах документа фрагменты drawing уже есть. Раньше один
    # такой фрагмент на любом листе отменял чтение листов целиком для всего
    # документа (core/drawing_processor.py). По умолчанию выключено.
    DRAWING_SHEET_MISSING_PAGES: bool = False
    # Растровый детектор: если по обычной маске лист не чертёж, рамка и
    # длинные линии ищутся ещё раз по маске, где тонкие линии не пропадают
    # при уменьшении (минимум по окну). Лист 4960 px с бледной рамкой иначе
    # уходил в плоское распознавание без Qwen-VL
    # (core/providers/raster_drawing.py). По умолчанию выключено.
    RASTER_FRAME_THIN_LINES: bool = False
    # Поле «материал» не получает допуск: марка 12Х18Н10Т давала «допуск H10»
    # (core/drawing_processor.py). По умолчанию выключено.
    DRAWING_MATERIAL_NO_TOLERANCE: bool = False
    # Скан чертежа в PDF читается так же полно, как лист-картинка: каждый
    # чертёжный лист уходит в Qwen-VL целиком (лист, штамп, таблицы) и
    # отдельным проходом «перепиши весь текст листа», даже если MinerU нарезал
    # из него виды. Без этого у скана PDF читались только вырезки видов, а
    # штамп, технические требования, общая шероховатость и размеры вне
    # вырезок оставались за распознаванием без модели
    # (core/drawing_processor.py, core/drawing_quality.py). По умолчанию выключено.
    DRAWING_PDF_FULL_READ: bool = False
    # На листе, весь текст которого переписан Qwen-VL, абзац распознавания
    # (MinerU/Tesseract) заменяется совпавшими строками модели: «Ра 16» → «Ra 1,6»,
    # «спровок» → «справок». Замена — только когда строки модели покрывают абзац
    # целиком и цифры в них те же; иначе абзац остаётся как был
    # (core/drawing_transcript.py). По умолчанию выключено.
    DRAWING_TRANSCRIPT_FIXES_OCR: bool = False
    # На листе, весь текст которого переписан Qwen-VL, запись распознавания
    # (таблица MinerU, абзац Tesseract) убирается, если всё её содержимое есть
    # у модели (повтор) или если в ней нет ни слова, ни правильно записанного
    # значения, которых у модели нет, а почти всё — обрывки (шум). Лексема,
    # которой у модели нет, оставляет запись на месте; при расхождении в
    # цифрах («7:1» против «1:1») остаются оба чтения, а чтение модели
    # кладётся рядом (core/drawing_stale_sources.py). По умолчанию выключено.
    DRAWING_SUPPRESS_STALE_ON_FULL_READ: bool = False
    # Мелкий шрифт на чертеже: (1) небольшая картинка (вырезка вида) перед
    # чтением увеличивается вдвое — на вырезке 700 px модель через раз читала
    # отклонение «2+1,5» как «2+15»; (2) в запросы к модели добавлено правило
    # про запятую в дробях и мелкие предельные отклонения; (3) в марке вида
    # «…Н11МЗ» буква «З» после «М» — это цифра 3
    # (core/providers/qwen_client.py). По умолчанию выключено.
    DRAWING_SMALL_PRINT_CARE: bool = False
    # Картинка с длинной стороной меньше этой считается небольшой.
    DRAWING_SMALL_IMAGE_SIDE: int = 1200
    # Числовая достоверность размеров и знаков (core/providers/
    # dimension_fidelity.py): восстанавливается запятая десятичной дроби
    # там, где запись без неё по ГОСТ невозможна («M28x15» → «M28x1,5»,
    # «Ра 16» → «Ra 1,6», «2+15» → «2+1,5»), раскрываются надстрочные
    # цифры отклонения со знаком («2⁺¹˙⁵»), правится масштаб не из ряда
    # ГОСТ 2.302 в графе «Масштаб» и в заголовке вида («7:1» → «1:1»),
    # марка стали больше не даёт допуска («12Х18Н10Т» без «H10»), а из двух
    # прочтений одного размера остаётся то, в котором сохранены «±» и
    # справочная звёздочка. Обозначение шва сверяется с ГОСТ 14771
    # («H1-ИНн» → «Н1-ИНп»), вырезка штампа читается увеличенной.
    # В запросы к модели добавляется правило про знак
    # отклонения и звёздочку. По умолчанию выключено.
    DRAWING_DIMENSION_FIDELITY: bool = False

    # ------------------------- Чертежи: разметка зрением + внешняя модель
    # Адрес хоста с моделью (vLLM, OpenAI-совместимый). По умолчанию — сосед
    # по compose: контейнер vllm на внутренней сети. Пустое значение выключает
    # ветку чертежей целиком, и это видно в логе: подменять разбор сплошным
    # распознаванием листа больше нечем и незачем.
    QWEN_ENDPOINT: Optional[str] = "http://vllm:8001/v1"
    QWEN_MODEL: str = "Qwen/Qwen3.8-27B-FP8"
    # vLLM внутри контура поднимается с --api-key local: ключ не секрет, но
    # без него OpenAI-клиенты отказываются слать запрос.
    QWEN_API_KEY: Optional[str] = "local"
    QWEN_TIMEOUT: int = 180
    # Повторы только на сетевых сбоях и 5xx: «модель ответила ерунду» не
    # повторяется.
    QWEN_RETRIES: int = 2
    QWEN_MAX_TOKENS: int = 4096
    QWEN_TEMPERATURE: float = 0.0
    # Длинная сторона листа и вырезанной области при отправке модели.
    QWEN_SHEET_MAX_SIDE: int = 2000
    QWEN_REGION_MAX_SIDE: int = 1600
    # Во сколько раз увеличивается вырезанная область: мелкий текст штампа
    # читается заметно лучше на увеличенном фрагменте.
    QWEN_REGION_UPSCALE: float = 2.0
    # Отдельный проход по основной надписи (DRAWING_TITLE_BLOCK_PASS): штамп
    # и колонка дополнительных граф читаются своим запросом, который просит
    # не свободный словарь, а графы ГОСТ 2.104 с подписями, рукописное
    # отдельной пометкой и обозначение со всеми точками. Без него в индекс
    # уходили значения без имени графы («12,35», «1:4»), а даты подписей,
    # «Инв. № подл.» и «Перв. примен.» не возвращались вовсе: старый промпт
    # прямо велел пропускать служебные графы бланка
    # (core/providers/title_block.py). По умолчанию выключено.
    DRAWING_TITLE_BLOCK_PASS: bool = False
    # Длинная сторона вырезки штампа. Отдельно от QWEN_REGION_MAX_SIDE,
    # потому что 1600 px отменяли увеличение вырезки: штамп A4 в 200 dpi
    # после QWEN_REGION_UPSCALE даёт около 2900 px и ужимался обратно.
    QWEN_TITLE_BLOCK_MAX_SIDE: int = 2600
    QWEN_TITLE_BLOCK_UPSCALE: float = 3.0
    # Колонка дополнительных граф у левого поля читается отдельным запросом.
    # Выключение оставляет только сам штамп.
    DRAWING_SIDE_COLUMN_READ: bool = True

    # Разметка листа зрением: выравнивание, рамка формата, сетки таблиц.
    # Выключение оставляет только чтение листа целиком.
    DRAWING_VISION_ENABLED: bool = True
    # Предел выправления наклона в градусах: скан кладут криво на градус-два,
    # а поворот на десять означает, что лист опознан неверно.
    DRAWING_DESKEW_LIMIT: float = 3.0
