    OCR_MIN_SIDE: int = 900

    # ------------------------------------------- Выбор модели распознавания
    # Каталог моделей Tesseract (`--tessdata-dir`). Пусто — системный
    # каталог образа, то есть пакеты Debian `tesseract-ocr-rus`
