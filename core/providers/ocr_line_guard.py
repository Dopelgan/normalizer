"""
Предохранители снятия линий таблиц на чертёжных листах.

Снятие линий (`ocr_prepare._line_mask`) задумано под скан таблицы с сеткой:
линия ячейки сливается с цифрой, и цифра не читается. На чертёжном листе
картина другая — лист и состоит из линий, и замер показал, что на нём
снятие отнимает больше, чем даёт:

* технические требования листа d3 — CER 0.267 со снятием против 0.223 без;
* двуязычная легенда листа d6 — 0.429 против 0.324;
* маркировка листа d3 — снятие не срабатывает вовсе (0 пикселей), 0.262
  в обоих случаях.

Числа — на тех же эталонных кропах и тем же способом счёта, которым
измерены модель и языковая связка (`ocr-prepare-eval-20261114/out/`).

Здесь два независимых предохранителя и одна починка устойчивости.

1. **Защита штрихов** (`stroke_guard`). Длинная тонкая серия чёрных
   пикселей — это либо одинокая линия сетки, либо линия вместе с
   перекладиной знака, который на ней лежит: серия непрерывна и через знак
   тоже, и знак пропадает вместе с линией. Отличить их можно по тому, что
   остаётся после снятия: у одинокой линии вокруг пусто, у пересечения
   чернила продолжаются и выше, и ниже снятой серии.
2. **Отказ от снятия** — решается вызывающей стороной, которая знает жанр
   листа; здесь только настройка `OCR_LINE_REMOVAL_SKIP`, читаемая
   `prepare_page`.
3. **Устойчивый порог** (`quantise`). Порог Отсу — один на лист, по
   гистограмме. Изменение длинной стороны на 0,2 % (3507 → 3500 px)
   сдвигает его ровно на один уровень (151 → 152, 149 → 150, 160 → 161), а
   вместе с ним меняется маска линий — на листе d1 это 2296 пикселей
   разницы и 182 прочитанных символа против 168. Округление порога до
   кратного `OCR_OTSU_THRESHOLD_STEP` убирает эту дрожь.

Все три по умолчанию выключены: при выключенных настройках подготовка
листа работает в точности как раньше.
"""

from __future__ import annotations

import numpy as np


def quantise(threshold: int, step: int) -> int:
    """Порог, округлённый до кратного `step`. `step <= 1` — как было."""
    if step <= 1:
        return threshold
    return int(max(0, min(255, round(threshold / step) * step)))


def _reach(mask: np.ndarray, axis: int, forward: bool, distance: int) -> np.ndarray:
    """Истинно там, где в пределах `distance` по направлению есть `mask`."""
    out = mask.copy()
    shifted = mask
    for _ in range(max(0, distance)):
        shifted = np.roll(shifted, 1 if forward else -1, axis=axis)
        # `roll` замыкает массив по кругу: обнуляем вошедший с другого края.
        if axis == 0:
            shifted[0 if forward else -1, :] = False
        else:
            shifted[:, 0 if forward else -1] = False
        out = out | shifted
    return out


def stroke_guard(black: np.ndarray, lines: np.ndarray, reach: int) -> np.ndarray:
    """
    Маска линий без тех пикселей, через которые проходит штрих знака.

    `black` — чернила листа, `lines` — что собрались снять, `reach` — на
    сколько пикселей за снятую серию смотреть в поисках продолжения
    штриха. Запас должен быть чуть больше самой толстой снимаемой линии,
    иначе продолжением штриха покажется сама линия.
    """
    if reach <= 0 or not lines.any():
        return lines
    survivors = black & ~lines
    crossing = (
        (_reach(survivors, 0, False, reach) & _reach(survivors, 0, True, reach))
        | (_reach(survivors, 1, False, reach) & _reach(survivors, 1, True, reach))
    )
    return lines & ~crossing
