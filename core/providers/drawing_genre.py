"""
Жанровый гейт: страница считается чертёжным листом только по собственным
признакам чертежа, а не по наличию линий.

Зачем. Род страницы решался одной геометрией: много векторных путей, рамка
почти во весь лист, пучок отрезков в правом нижнем углу. У страницы ПОК,
ТУ, ТЗ, договора или сертификата всё это есть: сетка таблицы даёт сотни
путей, обрамление таблицы — прямоугольник во весь лист, а штамп текстового
документа (ГОСТ 2.104, формы 2 и 2а) и нижние строки таблицы дают тот самый
пучок в зоне штампа. Поэтому «Программа обеспечения качества» и «ПОК 01.25»
получали десятки листов-чертежей: таблица в рамке выглядит как чертёж, если
смотреть только на линии.

Что здесь. Признаки берутся из того, как чертёж устроен по стандартам, а не
из того, сколько на листе отрезков:

* **Основная надпись по ГОСТ 2.104, форма 1.** Графы «Масса» и «Масштаб»
  есть только в форме 1 — основной надписи чертежей и схем. У текстовых
  документов применяются формы 2 и 2а, и этих граф в них нет. Это не
  статистика по корпусу, а состав форм стандарта, поэтому признак один
  решает исход.
* **Размерная нотация (ГОСТ 2.307, 2.309, 2.311).** Ø/⌀, R, M с числом,
  ±, Ra/Rz, знак шероховатости, поля допусков (H7, h6), углы в градусах.
  ГОСТ 2.307 требует на чертеже размеры, необходимые для изготовления, —
  поэтому у настоящего листа их много. Одиночное вхождение не считается:
  «болт М12», «±0,5» и «90°» встречаются и во фразе, и в ячейке таблицы.
* **Названия видов, разрезов и сечений (ГОСТ 2.305).** «Вид А», «А-А»,
  «Разрез», «Сечение», «View A», «Section B-B». Так подписывают изображения
  на листе, и только на листе.
* **Масштаб из ряда ГОСТ 2.302.** Ряд закрытый, произвольное «n:m» не в
  счёт: иначе признаком становилось бы любое соотношение в тексте.
* **Обозначение по ГОСТ 2.201** с кодом чертежа или без кода (деталь, СБ,
  ВО, ГЧ, МЧ, схемы Э3). Обозначение с кодом текстового документа (ТУ, РЭ,
  ПМ, ПЗ, ТД, УК, И) чертежом страницу не делает: это документ, а не лист,
  — и такое обозначение признаком не является.

Граница применимости. Гейт отвечает только там, где есть что читать: он
снимает жанр чертежа со страницы, на которой **есть текст** и в этом тексте
нет ни одного признака чертежа. Лист, текста с которого почти не снять
(скан без текстового слоя, чертёж, у которого в файле лежат только линии),
гейт не трогает — там положительных признаков не из чего взять, и
придумывать их значило бы терять настоящие чертежи. См. отчёт по ветке:
доля таких листов измерена.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Sequence

# ---------------------------------------------------------------- пороги
# Столько символов на странице уже достаточно, чтобы судить о её содержании.
# Ниже — сказать нечего: это лист, текст которого в файле не лежит, и
# решение остаётся за геометрией. 120 символов — это примерно две строки
# основной надписи (обозначение, наименование, «Лист», «Листов»): меньше не
# бывает даже у чертежа с заполненным штампом.
MIN_CHARS_TO_JUDGE = 120

# Столько размерных обозначений не набирает ни фраза, ни строка таблицы:
# одиночные «М12», «±0,5», «90°» встречаются в тексте постоянно, три разных
# вхождения — это уже простановка размеров по ГОСТ 2.307.
MIN_DIMENSION_MARKS = 3

# Сколько «веса» признаков нужно, чтобы считать лист чертёжным. Один слабый
# признак документ подделать может (обозначение ЕСКД стоит и в штампе ТУ,
# «вид» встречается во фразе, «1:50» — в ссылке на план); два независимых
# признака чертёжной традиции разом — уже устройство листа, а не совпадение.
# Основная надпись формы 1 весит два: по ГОСТ 2.104 она применяется только
# на чертежах и схемах.
REQUIRED_WEIGHT = 2

_NUMBER = r"\d+(?:[.,]\d+)?"

# --------------------------------------------------- основная надпись (2.104)
# Строка из одних подписей граф формы 1. MuPDF склеивает соседние графы
# («Лит. Масса Масштаб»), поэтому допускается любой их порядок; в прозе эти
# слова стоят внутри предложения, а не строкой целиком.
_FORM1_LABEL = re.compile(
    r"^\s*(?:(?:Лит\.?|Масса|Масштаб|Mass|Weight|Scale)[\s|]*)*"
    r"(?:Масса|Масштаб|Mass|Weight|Scale)"
    r"(?:[\s|]*(?:Лит\.?|Масса|Масштаб|Mass|Weight|Scale))*\s*$",
    re.IGNORECASE | re.MULTILINE,
)

# ------------------------------------------------- размеры (2.307/2.309/2.311)
# Кириллица здесь не прихоть: в российских САПР знак диаметра набирают
# «Ф», резьбу — «М», поля допусков — «Н7», «н6». Латинский шаблон такой
# лист не видит вовсе, и настоящий чертёж оказался бы без признаков.
_DIMENSION_PATTERNS: Sequence[re.Pattern] = (
    re.compile(r"[Ø⌀øΦφФ]\s*" + _NUMBER),                      # диаметр
    re.compile(r"(?:^|[\s(])R\s*" + _NUMBER, re.MULTILINE),     # радиус
    re.compile(r"(?:^|[\s(])[MМ]\s*" + _NUMBER + r"(?:\s*[xх×]\s*" + _NUMBER + r")?",
               re.MULTILINE),                                   # резьба
    re.compile(r"±\s*" + _NUMBER),                              # предельное отклонение
    re.compile(r"R[az]\s*" + _NUMBER),                          # шероховатость
    re.compile(r"[√∇]"),                                        # знак шероховатости
    # Поле допуска по ГОСТ 2.307 всегда стоит за номинальным размером
    # («Ø42H7», «40h6»), поэтому перед буквой требуется цифра: без этого
    # признаком становился любой заводской код вида «KUA70» или «ЗИ12».
    re.compile(r"\d\s?[HhJjKkNnPpSsEeFfGgНнКкРрЕе][sS]?\d{1,2}(?!\d)"),
    re.compile(_NUMBER + r"\s*°"),                              # угловой размер
)

# ------------------------------------------------------------- виды (2.305)
_VIEW_PATTERNS: Sequence[re.Pattern] = (
    re.compile(r"\bВид\s+[А-ЯA-Z]\b"),
    re.compile(r"\bView\s+[A-Z]\b", re.IGNORECASE),
    re.compile(r"\b(?:Разрез|Сечение)\b", re.IGNORECASE),
    re.compile(r"\bSection\s+[A-Z]", re.IGNORECASE),
    # Подпись разреза: «А-А» отдельной строкой. Во фразе дефис между
    # одиночными буквами не стоит, а в обозначениях рядом есть цифры.
    re.compile(r"^\s*([А-ЯA-Z])\s*[-–—]\s*\1\s*$", re.MULTILINE),
    re.compile(r"\b(?:повернуто|повёрнуто|развернуто|развёрнуто|увеличено)\b",
               re.IGNORECASE),
)

# ------------------------------------------------------------ масштаб (2.302)
# Ряд закрытый: уменьшение, натуральная величина, увеличение.
_SCALE_SERIES = (
    "1:1",
    "1:2", "1:2,5", "1:2.5", "1:4", "1:5", "1:10", "1:15", "1:20", "1:25",
    "1:40", "1:50", "1:75", "1:100", "1:200", "1:400", "1:500", "1:800", "1:1000",
    "2:1", "2,5:1", "2.5:1", "4:1", "5:1", "10:1", "20:1", "40:1", "50:1", "100:1",
)
_SCALE = re.compile(
    r"(?<![\d.,:])(?:" + "|".join(re.escape(s) for s in _SCALE_SERIES) + r")(?![\d.,:])"
)

# ------------------------------------------------------- обозначение (2.201)
# Четырёхбуквенный код организации, шесть цифр классификационной
# характеристики, три цифры порядкового номера, затем — код документа.
_DESIGNATION = re.compile(
    r"(?<![A-Za-zА-Яа-яЁё0-9])([А-ЯA-Z]{4})\s*\.?\s*(\d{6})\s*\.\s*(\d{3})"
    r"\s*([А-ЯA-Z0-9]{0,4})(?![0-9])"
)
# Коды чертежей и схем по ГОСТ 2.102 и 2.701. Пустой код — чертёж детали.
_DRAWING_CODES = frozenset((
    "", "СБ", "ВО", "ТЧ", "ГЧ", "МЭ", "МЧ", "УЧ", "АС", "ВС0",
    "Э1", "Э2", "Э3", "Э4", "Э5", "Э6", "Э7",
    "Г1", "Г2", "Г3", "Г4", "Г5", "Г6", "Г7",
    "П1", "П2", "П3", "П4", "П5", "П6", "П7",
    "К1", "К2", "К3", "К4", "К5", "К6", "К7",
    "Л1", "Л2", "Л3", "Л4", "Л5", "Л6", "Л7",
))
# Коды текстовых документов: обозначение с таким кодом принадлежит
# документу, а не листу, и признаком чертежа не является.
_TEXT_CODES = frozenset((
    "СП", "ВД", "ВП", "ВИ", "ТУ", "ПЗ", "РР", "ТБ", "ПМ", "ПД", "ТП",
    "РЭ", "ИМ", "ФО", "ПС", "УК", "ТД", "Д", "И", "ТЗ", "ПОК", "ЭД",
))


@dataclass
class Evidence:
    """Признаки чертежа, найденные в тексте самого листа."""

    chars: int = 0
    title_block_form1: bool = False
    dimension_marks: int = 0
    view_titles: int = 0
    scale_mark: bool = False
    drawing_designation: bool = False
    text_designation: bool = False
    weight: int = 0
    reasons: List[str] = field(default_factory=list)

    @property
    def judgeable(self) -> bool:
        """Текста на листе хватает, чтобы судить о его содержании."""
        return self.chars >= MIN_CHARS_TO_JUDGE

    @property
    def proves_drawing(self) -> bool:
        return self.weight >= REQUIRED_WEIGHT

    def as_dict(self) -> Dict[str, Any]:
        return {
            "chars": self.chars,
            "title_block_form1": self.title_block_form1,
            "dimension_marks": self.dimension_marks,
            "view_titles": self.view_titles,
            "scale_mark": self.scale_mark,
            "drawing_designation": self.drawing_designation,
            "text_designation": self.text_designation,
            "weight": self.weight,
            "judgeable": self.judgeable,
            "proves_drawing": self.proves_drawing,
            "reasons": list(self.reasons),
        }


def assess(text: str) -> Evidence:
    """Текст страницы -> положительные признаки того, что это лист чертежа."""
    evidence = Evidence(chars=len("".join((text or "").split())))
    if not text:
        return evidence

    if _FORM1_LABEL.search(text):
        evidence.title_block_form1 = True
        evidence.weight += 2
        evidence.reasons.append("основная надпись формы 1 (ГОСТ 2.104)")

    marks = 0
    for pattern in _DIMENSION_PATTERNS:
        marks += len(pattern.findall(text))
    evidence.dimension_marks = marks
    if marks >= MIN_DIMENSION_MARKS:
        evidence.weight += 2
        evidence.reasons.append(f"размерная нотация, вхождений {marks}")

    views = 0
    for pattern in _VIEW_PATTERNS:
        views += len(pattern.findall(text))
    evidence.view_titles = views
    if views:
        evidence.weight += 1
        evidence.reasons.append(f"подписи видов и разрезов, вхождений {views}")

    if _SCALE.search(text):
        evidence.scale_mark = True
        evidence.weight += 1
        evidence.reasons.append("масштаб из ряда ГОСТ 2.302")

    for match in _DESIGNATION.finditer(text):
        code = (match.group(4) or "").strip().upper()
        if code in _TEXT_CODES:
            evidence.text_designation = True
        elif code in _DRAWING_CODES:
            evidence.drawing_designation = True
    # Обозначение без кода документа стоит и в тексте ТЗ или ТУ («изделие
    # ТАДУ 421451.003 должно…»), поэтому само по себе оно слабое, а рядом с
    # обозначением текстового документа не значит ничего: страница
    # принадлежит этому документу, а не листу.
    if evidence.drawing_designation and not evidence.text_designation:
        evidence.weight += 1
        evidence.reasons.append("обозначение ЕСКД с кодом чертежа (ГОСТ 2.201)")

    # Обозначение с кодом текстового документа в основной надписи говорит,
    # какому документу принадлежит лист: лист РЭ — это лист РЭ, сколько бы
    # размеров ни стояло в его таблицах. Оговорка одна: чертёж, вплетённый в
    # текстовый документ, несёт свою основную надпись формы 1 — и тогда это
    # лист чертежа, а обозначение рядом принадлежит ссылке, а не листу.
    if evidence.text_designation and not evidence.title_block_form1:
        evidence.weight = 0
        evidence.reasons = ["обозначение ЕСКД с кодом текстового документа "
                            "(ГОСТ 2.102): лист принадлежит документу, а не чертежу"]

    return evidence


def gate(text: str) -> Dict[str, Any]:
    """
    Решение гейта по странице: `demote` — снять жанр чертежа.

    Снимается только с листа, текст которого прочитан и не содержит ни
    одного признака чертежа. Лист без текста остаётся на усмотрение
    геометрии: положительных признаков там взять неоткуда.
    """
    evidence = assess(text)
    verdict = evidence.as_dict()
    verdict["demote"] = bool(evidence.judgeable and not evidence.proves_drawing)
    return verdict


def enabled() -> bool:
    from core.config import settings

    return bool(getattr(settings, "DRAWING_GENRE_GATE", False))
