"""Мелкий шрифт бланка свидетельства — на настоящем тексте с прода.

Образец взят из документа `doc-3200eb32143f9a398e00ef83c91b31aa`, страница 1,
дословно из базы (запрос к `chunks.content->>'text'`). Он важен именно тем, что
распознавание прочитало «организациу» вместо «организации»: шаблон обязан
переживать такие описки, иначе на проде он не сработает ни разу.
"""

import pytest

from core import document_furniture
from core.config import settings

# Дословный отрывок с прода. Между «модификация» и «единства измерений» здесь
# 105 символов — шаблон допускает до 120, и запас нужен: длина этой вставки
# меняется от бланка к бланку.
REAL = (
    "000 «НТЛ-Прибор» (Общество с ограниченной ответственностью «НТЛ-Прибор») _ "
    "полное и краткое наименование организациу-поверителя Уникальный номер записи "
    "об аккредитации в реестре аккредитованных лиц RA.RU.312193 СВИДЕТЕЛЬСТВО О "
    "ПОВЕРКЕ № 003.1937809 Действительно до __ 20.07.2028 _ Средство измерений "
    "Средство измерений | наименование и обозначение типа, модификация (при "
    "наличии) средства измерений, регистрационный номер в Федеральном "
    "информационном фонде по обеспечению единства измерений, Преобразователь "
    "термоэлектрический ТХА-1187; Зав. номер 260024"
)


@pytest.fixture
def furniture(monkeypatch):
    monkeypatch.setattr(settings, "SCAN_DROP_FRAME_FURNITURE", True)


def test_captions_of_the_real_form_are_cut(furniture):
    """Обе подписи бланка снимаются, и значение становится рядом с подписью."""
    out, cut = document_furniture.without_splices(REAL)

    assert cut >= 2, "ожидались снятые подписи бланка"
    assert "наименование и обозначение типа" not in out
    assert "полное и краткое наименование организаци" not in out
    # Содержание бланка остаётся целиком: кто поверитель, номер свидетельства,
    # до какого числа действительно, что именно поверяли и его заводской номер.
    for kept in ("«НТЛ-Прибор»", "RA.RU.312193", "003.1937809", "20.07.2028",
                 "Преобразователь термоэлектрический ТХА-1187", "Зав. номер 260024"):
        assert kept in out, kept


def test_the_measured_thing_and_its_value_end_up_together(furniture):
    """Главное, за чем правка: «Средство измерений» и его значение рядом.

    До правки между ними стоял мелкий шрифт бланка на 150 символов, и подпись с
    значением расходились по разным чанкам — вопрос о заводском номере получал
    подпись без значения.
    """
    out, _ = document_furniture.without_splices(REAL)

    label = out.index("Средство измерений")
    value = out.index("Преобразователь термоэлектрический")
    between = out[label:value]
    assert len(between) < 60, "между подписью и значением осталось лишнее: " + between
